/**
 * 单调钟（issue #104）。
 *
 * 为什么不能拿 `Date.now()` 算「过了多久 / 还剩多久」：墙钟会跳。休眠唤醒后的 NTP
 * 步进校时、手动改时间、虚拟机快照恢复、和 Windows 双启动把 RTC 按本地时间写坏，
 * 都能让它前后跳上几分钟乃至几小时。`deadline = Date.now() + 8000` 遇上一次 60s
 * 回拨，那个「8s 上界」就变成 68s——超时不再兜底；往前跳则相反，好隧道被判超时。
 *
 * 单调钟只随真实流逝前进，与系统时间无关，是所有上界与窗口该用的那把尺。
 */

/**
 * 自进程启动起的毫秒数，单调不减。只可用于求差值，绝对值无意义。
 * @returns {number}
 */
export function monotonicMs() {
  return performance.now();
}
